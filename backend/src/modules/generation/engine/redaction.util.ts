/**
 * Deterministic confidentiality lint for client-facing output.
 *
 * Two guarantees were being enforced by prompt wording alone, and both leaked at least once: a proposal shipped
 * "handled with the support of a third-party vendor", and a financial note read "excl. third-party costs". This
 * module checks the RENDERED text instead of trusting the model to have remembered.
 *
 * It reports; it does not rewrite. A finding is a prompt for a human to look, because a legitimate sentence can
 * contain a flagged word and silent edits to client copy would be worse than a warning.
 */

export type RedactionKind = 'supplier' | 'confidentiality' | 'tooling';

export interface RedactionFinding {
  kind: RedactionKind;
  /** The matched text, as it appears in the output. */
  term: string;
  /** Surrounding words, so a reviewer can judge without opening the document. */
  context: string;
}

/**
 * Phrases that reveal a third party is involved in delivery. Riseup supplies and installs everything as far as
 * the client is concerned, so none of these belong in client-facing copy.
 */
const CONFIDENTIALITY_TERMS = [
  'third-party', 'third party', '3rd party', 'subcontractor', 'sub-contractor',
  'reseller', 'vendor', 'supplier', 'outsourced', 'white-label', 'white label',
];

/**
 * Phrases that disclose how the work is produced internally. Deliberately NOT a bare "AI" — Riseup builds AI
 * products, so "AI-powered attendance" is legitimate client copy while "AI-generated" is a disclosure.
 */
const TOOLING_TERMS = [
  'ai-generated', 'ai generated', 'ai-assisted', 'ai assisted', 'ai-native', 'ai-drafted',
  'claude', 'cursor', 'codex', 'copilot', 'chatgpt', 'openai', 'anthropic',
  'llm', 'large language model', 'language model', 'gpt-', 'prompt engineering',
  'code generation tool', 'generated by ai', 'written by ai',
];

/** Keys whose values never reach the client — internal reasoning, ids, icon names. */
const INTERNAL_KEYS = new Set(['id', 'type', 'icon', 'iconMap', 'locked', 'rationale', 'internalNote', 'position']);

/** Every client-facing string in a proposal document, flattened. */
export function collectClientFacingText(doc: unknown): string[] {
  const out: string[] = [];
  const walk = (node: unknown, key?: string): void => {
    if (key && INTERNAL_KEYS.has(key)) return;
    if (typeof node === 'string') {
      if (node.trim()) out.push(node);
      return;
    }
    if (Array.isArray(node)) {
      for (const v of node) walk(v);
      return;
    }
    if (node && typeof node === 'object') {
      for (const [k, v] of Object.entries(node as Record<string, unknown>)) walk(v, k);
    }
  };
  walk(doc);
  return out;
}

/** A few words either side of a match, collapsed onto one line. */
function contextAround(text: string, at: number, len: number): string {
  const from = Math.max(0, at - 45);
  const to = Math.min(text.length, at + len + 45);
  return `${from > 0 ? '…' : ''}${text.slice(from, to).replace(/\s+/g, ' ').trim()}${to < text.length ? '…' : ''}`;
}

/** Escape a supplier-supplied string so it can be used as a literal in a RegExp. */
function escapeRe(v: string): string {
  return v.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function scan(texts: string[], terms: string[], kind: RedactionKind, findings: RedactionFinding[]): void {
  for (const term of terms) {
    if (!term.trim()) continue;
    // \b is unreliable around punctuation-bearing terms ("third-party", "gpt-"), so bound on non-letters instead.
    const re = new RegExp(`(^|[^a-z0-9])(${escapeRe(term)})(?![a-z0-9])`, 'gi');
    for (const text of texts) {
      for (const m of text.matchAll(re)) {
        const at = (m.index ?? 0) + m[1].length;
        findings.push({ kind, term: m[2], context: contextAround(text, at, m[2].length) });
      }
    }
  }
}

/**
 * Lint rendered client-facing text. `supplierTerms` are identifiers taken from a parsed vendor quotation —
 * company name, contact names, emails, phone numbers — which must never appear in what the client reads.
 */
export function lintRedaction(texts: string[], supplierTerms: string[] = []): RedactionFinding[] {
  const findings: RedactionFinding[] = [];
  // Supplier identifiers first: a leaked company name is more damaging than a generic word.
  scan(texts, supplierTerms.filter((t) => t && t.trim().length >= 3), 'supplier', findings);
  scan(texts, CONFIDENTIALITY_TERMS, 'confidentiality', findings);
  scan(texts, TOOLING_TERMS, 'tooling', findings);
  return findings;
}

/** One line per finding, ready for the change log. Deduplicated, most damaging kind first. */
export function summariseRedaction(findings: RedactionFinding[]): string[] {
  const order: RedactionKind[] = ['supplier', 'confidentiality', 'tooling'];
  const label: Record<RedactionKind, string> = {
    supplier: 'Supplier identity may be exposed',
    confidentiality: 'Reveals an outside party is involved',
    tooling: 'Discloses internal tooling',
  };
  const seen = new Set<string>();
  const lines: string[] = [];
  for (const kind of order) {
    for (const f of findings.filter((x) => x.kind === kind)) {
      const key = `${kind}:${f.term.toLowerCase()}`;
      if (seen.has(key)) continue;
      seen.add(key);
      lines.push(`${label[kind]} — “${f.term}” in: ${f.context}`);
    }
  }
  return lines;
}
